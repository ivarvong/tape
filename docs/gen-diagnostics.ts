// docs/gen-diagnostics.ts: docs/diagnostics.md, every code the compiler gives with what it means, made from
// compiler/diagnostics.ts, and for each code the section of LANGUAGE.md and of docs/guide.md that names it.
//   node docs/gen-diagnostics.ts           write docs/diagnostics.md
//   node docs/gen-diagnostics.ts --check   exit 1 when docs/diagnostics.md is not what this writes
// Whether the table has a row for every code the compiler gives, and a test for each, is test/diagnostics.ts's.
import { readFileSync, writeFileSync } from 'node:fs';
import { DIAGNOSTICS, RESERVED } from '../compiler/diagnostics.ts';

const OUT = new URL('./diagnostics.md', import.meta.url);
const read = (path: string): string => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');

/** GitHub's anchor of a heading: its text in lower case, without punctuation, a hyphen for each space. */
const slug = (heading: string): string =>
  heading
    .toLowerCase()
    .replaceAll(/[^\p{L}\p{N}\p{M} _-]/gu, '')
    .replaceAll(' ', '-');

/** The codes a text names: `C14`, and each of a range, `C83-C85` (or with an en dash). */
function named(text: string): Set<string> {
  const out = new Set<string>();
  for (const m of text.matchAll(/\b([CLP])(\d\d)(?:[-–]\1?(\d\d))?\b/g)) {
    const [, letter = '', from = '', to] = m;
    const last = to === undefined ? Number(from) : Number(to);
    for (let n = Number(from); n <= last; n++) out.add(`${letter}${String(n).padStart(2, '0')}`);
  }
  return out;
}

/** For each code, the section of a file (by its `##` or `###` heading) that explains it: the first whose table has
 * a row for it (`| C54 | …`, as the guide's tables of rules have), else the first that names it. */
function sections(path: string): Map<string, string> {
  const first = new Map<string, string>(),
    row = new Map<string, string>();
  let heading = '';
  let fenced = false;
  const body: string[] = [];
  const close = (): void => {
    if (heading !== '') {
      for (const c of named(body.join('\n'))) if (!first.has(c)) first.set(c, heading);
      for (const line of body)
        for (const c of named(/^\| ([^|]*) \|/.exec(line)?.[1] ?? '')) if (!row.has(c)) row.set(c, heading);
    }
    body.length = 0;
  };
  for (const line of read(path).split('\n')) {
    if (line.startsWith('```')) fenced = !fenced;
    const h = fenced ? null : /^#{2,3} (.+)$/.exec(line);
    if (h) {
      close();
      heading = (h[1] ?? '').trim();
    } else body.push(line);
  }
  close();
  return new Map([...first, ...row]);
}

const PLACES = [
  { path: 'LANGUAGE.md', link: '../LANGUAGE.md', name: 'LANGUAGE.md' },
  { path: 'docs/guide.md', link: 'guide.md', name: 'the guide' },
].map(p => ({ ...p, first: sections(p.path) }));

const cell = (s: string): string => s.replaceAll('|', '\\|');
const where = (code: string): string =>
  PLACES.flatMap(p => {
    const h = p.first.get(code);
    return h === undefined ? [] : [`[${p.name}: ${cell(h.replaceAll('`', ''))}](${p.link}#${slug(h)})`];
  }).join('; ');

const LETTERS =
  'A code starts with the part of the compiler that gives it: L for the lexer (the characters of a file), P for the parser (its shape), C for the checker and the rules (what it means). A refusal is a code, a file and line, what is wrong there, and what to write instead; the line and the fix name what the program wrote. This page says what each code refuses whatever the program, and where [LANGUAGE.md](../LANGUAGE.md) or [the guide](guide.md) explains it.';

function page(): string {
  const rows = Object.entries(DIAGNOSTICS).map(([code, d]) => `| ${code} | ${cell(d.meaning)} | ${where(code)} |`);
  const reserved = Object.entries(RESERVED).map(([code, why]) => `| ${code} | ${cell(why)} |`);
  return `${[
    '# Diagnostics',
    '',
    '<!-- Generated by `node docs/gen-diagnostics.ts` from compiler/diagnostics.ts, LANGUAGE.md and docs/guide.md. Do not edit: edit compiler/diagnostics.ts and run it again. `node docs/gen-diagnostics.ts --check` (in proof/all.ts) fails when this file is stale; test/diagnostics.ts fails when a code the compiler gives has no row, or no test that makes the compiler give it. -->',
    '',
    LETTERS,
    '',
    `${rows.length} codes.`,
    '',
    '| Code | Refuses | Explained in |',
    '|---|---|---|',
    ...rows,
    '',
    '## Reserved',
    '',
    'These codes are kept for rules that are written down and not shipped. The compiler gives none of them.',
    '',
    '| Code | For |',
    '|---|---|',
    ...reserved,
  ].join('\n')}\n`;
}

const fresh = page();
if (process.argv.includes('--check')) {
  let written: string | null;
  try {
    written = readFileSync(OUT, 'utf8');
  } catch {
    written = null;
  }
  const n = Object.keys(DIAGNOSTICS).length;
  if (written === fresh)
    console.log(`docs/diagnostics.md is current: ${n} codes, ${Object.keys(RESERVED).length} reserved`);
  else {
    console.log('FAIL docs/diagnostics.md is stale: run node docs/gen-diagnostics.ts');
    process.exit(1);
  }
} else {
  writeFileSync(OUT, fresh);
  console.log(`wrote docs/diagnostics.md (${fresh.length} bytes)`);
}
